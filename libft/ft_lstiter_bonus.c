#include "libft.h"

void	ft_lstiter(t_list *lst, void (*f)(void *))
{
	if (!lst)
		return ;
	while (lst->next)
	{
		f(lst->content);
		lst = lst->next;
	}
	f(lst->content);
}

/*lst: The address of a pointer to a node.
f: The address of the function used to iterate on
the list.
None
None
Iterates the list ’lst’ and applies the function
’f’ on the content of each node.*/
